const uint8_t *cyr_get_glyph(uint32_t cp) {
    if (cp == 0x0401) return yo_up;
    if (cp == 0x0451) return yo_lo;
    if (cp >= 0x0410 && cp <= 0x042F) return up[cp - 0x0410];
    if (cp >= 0x0430 && cp <= 0x044F) return lo[cp - 0x0430];
    return (const uint8_t *)0;
}
